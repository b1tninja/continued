import type { ShellKind } from "../../../util/shell";
import { classifyReadOnly } from "../readOnlyCommand";
import { keyOf, scan } from "./verdictHarness";
import { casesFor } from "./verdicts";

const SHELLS: ShellKind[] = ["bash", "zsh", "sh", "powershell", "cmd"];

const GIT_CLEAN = {
  cwd: "/repo",
  home: "/home/u",
  readGitConfig: () => "",
  probe: () => undefined,
};

const pct = (a: number, b: number) =>
  b === 0 ? "n/a" : `${Math.round((100 * a) / b)}%`;

/**
 * The report in plans/command-analysis-report.md: what each scanner makes of
 * the verdict corpus, per shell. Written by `WRITE_CORPUS_REPORT=1 npx vitest
 * run tools/permissions/corpus`, and checked against the file in the
 * repository by verdictReport.vitest.ts, so it cannot go stale.
 */
export function buildReport(): string {
  const out: string[] = [];
  out.push(
    "# Command analysis: what the scanners make of the corpus",
    "",
    "Generated by `core/tools/permissions/corpus/verdictReport.ts` from `verdicts.ts` (plans/command-analysis.md, P0). Do not edit by hand: regenerate with `WRITE_CORPUS_REPORT=1 npx vitest run tools/permissions/corpus` from `core/`.",
    "",
    "Each case says what is true of a command in a shell: it **reads**, it **writes**, or it is **unsure**. A scanner may say less than the truth (unsure for a read), but it must never say more: vouching for a command that is not read-only is **unsound**, and the build fails on it.",
    "",
    "## The read-only classifier",
    "",
    "| Shell | Cases | Reads | Writes | Unsure | Vouched | Vouched share of reads | Unsound |",
    "| ----- | ----- | ----- | ------ | ------ | ------- | ---------------------- | ------- |",
  );
  const misses: Record<string, string[]> = {};
  for (const shell of SHELLS) {
    const cases = casesFor(shell);
    const count = (v: string) => cases.filter((k) => k.verdict === v).length;
    const vouched = cases.filter((k) => scan(k, shell).vouched);
    const reads = cases.filter((k) => k.verdict === "reads");
    const unsound = vouched.filter((k) => k.verdict !== "reads");
    out.push(
      `| ${shell} | ${cases.length} | ${count("reads")} | ${count("writes")} | ${count("unsure")} | ${vouched.length} | ${pct(vouched.filter((k) => k.verdict === "reads").length, reads.length)} | ${unsound.length} |`,
    );
    misses[shell] = reads
      .filter((k) => !scan(k, shell).vouched)
      .map((k) => {
        const r = classifyReadOnly(k.command, { shell, ...GIT_CLEAN });
        return `- \`${k.command}\`: ${r.vouched ? "" : r.why}`;
      });
  }

  out.push(
    "",
    "## Reads the classifier does not vouch for",
    "",
    "The work list for the parsers: each is truly read-only, and the reason is what the classifier said. A fix removes a line here.",
    "",
  );
  for (const shell of SHELLS) {
    out.push(`### ${shell}`, "");
    out.push(...(misses[shell].length ? misses[shell] : ["None."]), "");
  }

  const gaps = (pick: (shell: ShellKind) => string[]) =>
    SHELLS.flatMap(pick).sort();
  const protectGaps = gaps((shell) =>
    casesFor(shell)
      .filter((k) => k.protects && scan(k, shell).protectsFound !== k.protects)
      .map(
        (k) =>
          `- ${keyOf(shell, k)}: wanted ${k.protects}, found ${scan(k, shell).protectsFound}`,
      ),
  );
  const resolveGaps = gaps((shell) =>
    casesFor(shell)
      .filter((k) => k.resolves && !scan(k, shell).resolvesOk)
      .map(
        (k) => `- ${keyOf(shell, k)}: a text rule should see \`${k.resolves}\``,
      ),
  );
  out.push(
    "## The protected-path scan",
    "",
    `Cases with an expectation: ${SHELLS.flatMap((s) => casesFor(s)).filter((k) => k.protects).length}.`,
    "",
    ...(protectGaps.length ? protectGaps : ["No disagreements."]),
    "",
    "## The text a deny or ask rule is tried against",
    "",
    `Cases with an expectation: ${SHELLS.flatMap((s) => casesFor(s)).filter((k) => k.resolves).length}.`,
    "",
    ...(resolveGaps.length ? resolveGaps : ["No disagreements."]),
    "",
  );
  return out.join("\n");
}
