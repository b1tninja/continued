import type { ShellKind } from "../../../util/shell";
import type { VerdictCase } from "./verdicts";

/**
 * Environment-variable assignments in a command line (ROADMAP: command
 * analysis, assignment prefix). Each case is labelled with what is TRUE of the
 * command, as in verdicts.ts, and with what the assignment scan must say:
 *
 * - dangerous: the name loads code or changes which program runs; asks at
 *   every level, IDGAF included
 * - sensitive: redirects configuration, credentials, network or temp files;
 *   asks below IDGAF
 * - none: no ask on the assignment (harmless, unknown, or not an assignment)
 *
 * `resolves` is what a deny or ask rule written as text must still see after
 * the assignments. A prefix is never read as read-only (`reads` is never the
 * verdict here): an environment prefix can change what runs.
 */
export type EnvLabel = "dangerous" | "sensitive" | "none";

export interface EnvVerdictCase extends VerdictCase {
  env: EnvLabel;
}

const POSIX: ShellKind[] = ["bash", "zsh", "sh"];
const PS: ShellKind[] = ["powershell"];
const CMD: ShellKind[] = ["cmd"];

const e = (
  shells: ShellKind[],
  command: string,
  verdict: VerdictCase["verdict"],
  env: EnvLabel,
  why: string,
  resolves?: string,
): EnvVerdictCase => ({
  shells,
  command,
  verdict,
  env,
  why,
  ...(resolves ? { resolves } : {}),
});

